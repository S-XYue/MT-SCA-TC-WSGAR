class Transformer(nn.Module):

    def __init__(self, d_model=512, nhead=8, num_decoder_layers=6, num_encoder_layers=6,
                 dim_feedforward=2048, dropout=0.1,
                 activation="relu", normalize_before=False,
                 return_intermediate_dec=False):
        super().__init__()

        # decoder_layer = TransformerDecoderLayer(d_model, nhead, dim_feedforward,
        #                                         dropout, activation, normalize_before)
        decoder_layer2 = TransformerDecoderLayer2(d_model, nhead, dim_feedforward,
                                                  dropout, activation, normalize_before)
        decoder_norm = nn.LayerNorm(d_model)
        # self.decoder = TransformerDecoder(decoder_layer, num_decoder_layers, decoder_norm,
        #                                   return_intermediate=return_intermediate_dec)

        self.encoder = TransformerBlock(dim=d_model, num_heads=nhead, ffn_expansion_factor=2.66, bias=False,
                                        LayerNorm_type='WithBias')  # ffn_expansion_factor=2.66

        self.decoder2 = TransformerDecoder(decoder_layer2, num_decoder_layers, decoder_norm,
                                           return_intermediate=return_intermediate_dec)

        self._reset_parameters()

        self.d_model = d_model
        self.nhead = nhead
        self.norm = nn.LayerNorm(d_model)
        self.dropout = nn.Dropout(dropout)

    def _reset_parameters(self):
        for p in self.parameters():
            if p.dim() > 1:
                nn.init.xavier_uniform_(p)

    def forward(self, src, mask, query_embed, pos_embed):
        # flatten NxCxHxW to HWxNxC
        bs, c, h, w = src.shape
        # src = src.flatten(2).permute(2, 0, 1)
        pos_embed1 = pos_embed
        pos_embed = pos_embed.flatten(2).permute(2, 0, 1)
        query_embed = query_embed.unsqueeze(1).repeat(1, bs, 1)  # 9,256

        src1 = self.encoder(src, pos_embed1)

        src = src + self.dropout(src1)
        src = src.permute(0, 2, 3, 1)
        src = self.norm(src)
        src = src.permute(0, 3, 1, 2)

        src = src.flatten(2).permute(2, 0, 1)

        tgt = torch.zeros_like(query_embed)  # 8 10 256
        # tgt = query_embed
        hs, att = self.decoder2(tgt, src, memory_key_padding_mask=mask,
                                pos=pos_embed, query_pos=query_embed)  # pos=pos_embed

        return hs.transpose(1, 2), att


class TransformerDecoder(nn.Module):

    def __init__(self, decoder_layer, num_layers, norm=None, return_intermediate=False):
        super().__init__()
        self.layers = _get_clones(decoder_layer, num_layers)
        self.num_layers = num_layers
        self.norm = norm
        self.return_intermediate = return_intermediate

    def forward(self, tgt, memory,
                tgt_mask: Optional[Tensor] = None,
                memory_mask: Optional[Tensor] = None,
                tgt_key_padding_mask: Optional[Tensor] = None,
                memory_key_padding_mask: Optional[Tensor] = None,
                pos: Optional[Tensor] = None,
                query_pos: Optional[Tensor] = None):
        output = tgt
        att = None

        intermediate = []
        intermediate_att = []

        for layer in self.layers:
            output, att = layer(output, memory, tgt_mask=tgt_mask,
                                memory_mask=memory_mask,
                                tgt_key_padding_mask=tgt_key_padding_mask,
                                memory_key_padding_mask=memory_key_padding_mask,
                                pos=pos, query_pos=query_pos)
            if self.return_intermediate:
                intermediate.append(self.norm(output))
                intermediate_att.append(att)

        if self.norm is not None:
            output = self.norm(output)
            if self.return_intermediate:
                intermediate.pop()
                intermediate.append(output)

        if self.return_intermediate:
            return torch.stack(intermediate), torch.stack(intermediate_att)

        return output.unsqueeze(0), att.unsqueeze(0)


